// IMAGE_ALT map already documents for itself: a registry MISS is not an
// error, it is the ordinary shape for the large majority of names in the
// Notion Skills database that this curated redesign (owner decision,
// 2026-08-12 -- "too many chips reads as overclaiming") never asked for an
// icon. Every call site in SkillsBand.tsx reads this map with `?? <fallback>`
// rather than assuming a hit, exactly like ProjectCard's own
// `IMAGE_ALT[project.imageSrc] ?? '...'`.
//
// Sources (package names only -- no URLs live in this file on purpose, so
// the redesign's own gate against external references in this exact file
// stays clean):
//   - Brand marks (python, salesforce, supabase, notion, vercel, swift,
//     googlesheets, anthropic): simple-icons, CC0. Every <path> below was
//     fetched verbatim via `curl` against the published package and copied
//     byte-for-byte -- never hand-authored or approximated from memory,
//     since a hand-drawn "python-ish" glyph would be a worse trademark than
//     no glyph at all.
//   - Concept marks (trending-up, store, clipboard-check, database,
//     bar-chart-3, graduation-cap): lucide-static, ISC. Also fetched
//     verbatim. Lucide ships stroke glyphs (fill="none", stroke=
//     "currentColor", several <path>/<rect>/<ellipse> children per icon),
//     the opposite construction from simple-icons' single filled <path> --
//     ConceptIcon below keeps that stroke wrapper intact rather than
//     flattening it into a fill shape, which would mean redrawing the icon,
//     not just relaying out its own real path data.
//
// Both wrappers key color off `currentColor` and set no width/height of
// their own (viewBox does the scaling) -- every render site in SkillsBand.tsx
// supplies the actual pixel size and color (text-peri / text-on-dark-soft)
// via a wrapping element, the same "size lives at the call site, not the
// asset" split ProjectCard's own <img width={800} height={450}> takes for
// its two known fixture images.

// simple-icons: single filled <path>, viewBox 0 0 24 24 -- every brand glyph
// this package ships already matches this exact shape.
function BrandIcon({ path }: { path: string }): ReactNode {
  return (
    <svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" className="h-full w-full">
      <path d={path} />
    </svg>
  );
}

// lucide-static: stroke wrapper shared by every concept glyph below. The
// four stroke-* attributes are copied from lucide's own <svg> opening tag
// (width/height/class dropped -- BrandIcon's own reasoning above).
function ConceptIcon({ children }: { children: ReactNode }): ReactNode {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className="h-full w-full"
    >
      {children}
    </svg>
  );
}

